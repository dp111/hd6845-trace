#!/usr/bin/env python3
"""Generate trace/decode.txt, the geometry of the register decode array, from
trace/decode_matrix.json (written by tools/pla_read.py).

The array is too regular to be worth drawing by hand: positions of the columns, rows,
rails and pads are measured, and what varies from cell to cell (which pads exist,
which side of a pad carries a transistor) comes from the measured matrix. Shapes are
rectangles with measured centres and typical sizes, not outlines of each feature.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PH = 13          # half height of a poly row
BAND_OF_ROW = 'ABBCCDDEEF'


def main():
    m = json.load(open(os.path.join(ROOT, 'trace', 'decode_matrix.json')))
    xs, ys, pads, T, addr = m['columns_x'], m['rows_y'], m['pads'], m['transistors'], m['address_of_column']
    o = []
    w = o.append
    w('# Register decode array, x 14140-15800, y 13500-14670.')
    w('# GENERATED by tools/gen_decode.py from trace/decode_matrix.json. Do not edit by hand:')
    w('# re-run tools/pla_read.py (reads the array from the clean shot) and then gen_decode.py.')
    w('#')
    w('# A NOR plane. 18 metal columns, each with a depletion load from the VCC bus along the')
    w('# top. Ten poly rows in five pairs: pair k carries address bit k, upper row the true')
    w('# line (ar<k>), lower row the complement (ar<k>_n). Between the two rows of a pair runs')
    w('# a ground diffusion rail. A column has contact pads between the pairs; a transistor is')
    w('# where a pad\'s diffusion runs under a row to the rail. Each column has exactly one')
    w('# transistor per pair, so it is high for exactly one address: rsel<N>.')
    w('# Row names assume the rows are driven straight from the address register; their')
    w('# drivers (to the right of the array) are not traced yet.')
    w('@block decode')
    w('')
    w('M 14140,13480:14200,14700          # VSS bus down the left side')
    w('N M 14170,14000 vss')
    w('M 14225,13518:15780,13632          # VCC bus along the top')
    w('N M 15000,13560 vcc')
    w('')
    w('# ---- rows')
    for r, y in enumerate(ys):
        name = f'ar{r // 2}' + ('_n' if r % 2 else '')
        w(f'P 14225,{y - PH}:15800,{y + PH}')
        w(f'N P 15790,{y} {name}')
    w('')
    w('# ---- ground rails, one per pair, each contacted to the VSS bus at its left end')
    for k in range(5):
        y0, y1 = ys[2 * k] + PH, ys[2 * k + 1] - PH
        w(f'D 14150,{y0}:15775,{y1}')
        w(f'C 14165,{(y0 + y1) // 2} s=24x30')
    w('')
    for c, x in enumerate(xs):
        x = round(x)
        w(f'# ---- column {c + 1}: address {addr[c]}')
        w(f'M {x - 13},13652:{x + 13},14662')
        w(f'N M {x},14655 rsel{addr[c]}')
        # load: VCC pad, channel under the load gate, output pad; gate tied to the output
        a_bot = ys[0] - PH - 3 if not T[0][c] else ys[0] + PH + 3     # pad A, with its tab if any
        top_bot = a_bot if pads['A'][c] else 13700
        w(f'D {x - 22},13525:{x + 22},{top_bot}')
        w(f'C {x},13553 s=26x26')                 # to the VCC bus
        w(f'P {x - 30},13590:{x + 48},13645')     # load gate
        w(f'P {x + 26},13640:{x + 48},13690')     # ... leg down to its buried contact
        w(f'D {x + 20},13655:{x + 48},13690')
        w(f'B {x + 24},13653:{x + 50},13692')
        w(f'C {x},13676 s=24x24')                 # output pad to the column
        if pads['A'][c]:
            w(f'C {x},13722 s=24x24')
        # pads B..E between the pairs, F below the last row; tabs under the rows that have a transistor
        for bi, b in enumerate('BCDEF'):
            if not pads[b][c]:
                continue
            up_row = 2 * bi + 1                    # row above the pad (index)
            dn_row = 2 * bi + 2 if b != 'F' else None
            y0 = ys[up_row] + PH + 6
            y1 = (ys[dn_row] - PH - 6) if dn_row is not None else ys[up_row] + PH + 70
            if T[up_row][c]:
                y0 = ys[up_row] - PH - 3           # run under the row above, into its rail
            if dn_row is not None and T[dn_row][c]:
                y1 = ys[dn_row] + PH + 3           # run under the row below, into its rail
            w(f'D {x - 20},{y0}:{x + 20},{y1}')
            cy = (ys[up_row] + PH + (ys[dn_row] - PH if dn_row is not None else ys[up_row] + PH + 76)) // 2
            w(f'C {x},{cy} s=24x24')
        w('')
    with open(os.path.join(ROOT, 'trace', 'decode.txt'), 'w') as f:
        f.write('\n'.join(o) + '\n')
    print('wrote trace/decode.txt,', len(o), 'lines')


if __name__ == '__main__':
    main()
